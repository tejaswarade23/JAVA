package calculator;

public class Calculator {

	public int add(int num1,int num2) {
		return num1+num2;
	}
	
	public float add(float num1,float num2) {
		return num1+num2;
	}
	
	public double add(double num1,double num2) {
		return num1+num2;
	}
	
	public float add(float num1,int num2) {
		return num1+num2;
	}
	
	public double add(float num1,double num2) {
		return num1+num2;
	}
	
	public double add(int num1,double num2) {
		return num1+num2;
	}
	
	
	public float substract(float num1,float num2) {
		return num1-num2;
	}
		
	public float multiplication(float num1,float num2) {
		return num1*num2;
	}
	
	public float division(float num1,float num2) {
		return num1/num2;
	}
	
	public float modulus(float num1,float num2) {
		return num1%num2;
	}
	
}
